import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { createCipheriv, createDecipheriv, randomBytes } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, rename, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { Readable } from 'node:stream';
import { env } from './env.js';

// Spec #33 — evidence storage behind one interface so the backend can move from local disk
// to MinIO/S3 (§21) without touching the evidence module. Keys look like
// "incidents/BIRDS-2026-1021/<uuid>.jpg" and are always generated by the server.
export interface StorageDriver {
  put(key: string, data: Buffer): Promise<void>;
  get(key: string): Promise<Readable | null>; // null when the object does not exist
  read(key: string): Promise<Buffer | null>;
  remove(key: string): Promise<void>; // only used to roll back failed uploads
}

const KEY_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._/-]*$/;

function checkKey(key: string) {
  // Defence in depth against path traversal, even though keys are server-generated
  if (!KEY_PATTERN.test(key) || key.includes('..')) throw new Error(`Invalid storage key: ${key}`);
}

class LocalDiskStorage implements StorageDriver {
  private readonly root = path.resolve(env.EVIDENCE_DIR);

  private resolve(key: string) {
    checkKey(key);
    const full = path.resolve(this.root, key);
    if (!full.startsWith(this.root + path.sep)) throw new Error(`Storage key escapes root: ${key}`);
    return full;
  }

  async put(key: string, data: Buffer) {
    const full = this.resolve(key);
    await mkdir(path.dirname(full), { recursive: true });
    // Write then rename so a crash never leaves a half-written file under the final name
    const tmp = `${full}.${process.pid}.partial`;
    await writeFile(tmp, data, { flag: 'wx', mode: 0o640 });
    await rename(tmp, full);
  }

  async get(key: string) {
    const full = this.resolve(key);
    try {
      await stat(full);
    } catch {
      return null;
    }
    return createReadStream(full);
  }

  async read(key: string) {
    const stream = await this.get(key);
    if (!stream) return null;
    const chunks: Buffer[] = [];
    for await (const chunk of stream) chunks.push(chunk as Buffer);
    return Buffer.concat(chunks);
  }

  async remove(key: string) {
    await rm(this.resolve(key), { force: true });
  }
}

// ---------------------------------------------------------------------------
// Spec #33 — S3-compatible object storage (§21): MinIO, AWS S3, or Supabase Storage for the
// Render demo. The bucket must be private; the API is the only reader and writer, and objects
// are encrypted by EncryptedStorage before they leave the process.
// ---------------------------------------------------------------------------

/** The part of S3Client the driver uses (tests pass a fake). */
export interface S3Sender {
  send(command: PutObjectCommand | GetObjectCommand | DeleteObjectCommand): Promise<unknown>;
}

const isNotFound = (err: unknown) => {
  const e = err as { name?: string; $metadata?: { httpStatusCode?: number } };
  return e?.name === 'NoSuchKey' || e?.name === 'NotFound' || e?.$metadata?.httpStatusCode === 404;
};

export class S3Storage implements StorageDriver {
  constructor(
    private readonly client: S3Sender,
    private readonly bucket: string,
  ) {}

  async put(key: string, data: Buffer) {
    checkKey(key);
    // A single PUT is atomic: the object appears complete or not at all
    await this.client.send(
      new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: data, ContentLength: data.length, ContentType: 'application/octet-stream' }),
    );
  }

  async read(key: string) {
    checkKey(key);
    try {
      const res = (await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }))) as {
        Body?: { transformToByteArray(): Promise<Uint8Array> };
      };
      return res.Body ? Buffer.from(await res.Body.transformToByteArray()) : null;
    } catch (err) {
      if (isNotFound(err)) return null;
      throw err;
    }
  }

  async get(key: string) {
    const data = await this.read(key);
    return data ? Readable.from(data) : null;
  }

  async remove(key: string) {
    checkKey(key);
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

function s3FromEnv() {
  const client = new S3Client({
    region: env.S3_REGION,
    endpoint: env.S3_ENDPOINT,
    forcePathStyle: env.S3_FORCE_PATH_STYLE,
    credentials: { accessKeyId: env.S3_ACCESS_KEY_ID!, secretAccessKey: env.S3_SECRET_ACCESS_KEY! },
    // Newer SDKs add CRC checksums to every request; not all S3-compatible stores accept them
    requestChecksumCalculation: 'WHEN_REQUIRED',
    responseChecksumValidation: 'WHEN_REQUIRED',
  });
  return new S3Storage(client, env.S3_BUCKET!);
}

// ---------------------------------------------------------------------------
// Spec #27 — encryption at rest. Wraps any driver (local disk or S3).
// Format: "BIRDSEV1" | iv (12) | GCM tag (16) | ciphertext. The storage key is authenticated as
// additional data, so a file copied onto another record's key fails to decrypt. Objects without
// the header (stored before encryption was enabled) are returned as they are.
// ---------------------------------------------------------------------------
const MAGIC = Buffer.from('BIRDSEV1');
const IV_LEN = 12;
const TAG_LEN = 16;

export class EncryptedStorage implements StorageDriver {
  constructor(
    private readonly inner: StorageDriver,
    private readonly key: Buffer,
  ) {
    if (key.length !== 32) throw new Error('Evidence encryption key must be 32 bytes');
  }

  async put(key: string, data: Buffer) {
    const iv = randomBytes(IV_LEN);
    const cipher = createCipheriv('aes-256-gcm', this.key, iv);
    cipher.setAAD(Buffer.from(key));
    const body = Buffer.concat([cipher.update(data), cipher.final()]);
    await this.inner.put(key, Buffer.concat([MAGIC, iv, cipher.getAuthTag(), body]));
  }

  async read(key: string) {
    return (await this.readDetailed(key))?.data ?? null;
  }

  /** Like read(), and says whether the object was stored encrypted (false = legacy plaintext). */
  async readDetailed(key: string): Promise<{ data: Buffer; encrypted: boolean } | null> {
    const raw = await this.inner.read(key);
    if (!raw) return null;
    if (raw.length < MAGIC.length + IV_LEN + TAG_LEN || !raw.subarray(0, MAGIC.length).equals(MAGIC)) return { data: raw, encrypted: false };
    const iv = raw.subarray(MAGIC.length, MAGIC.length + IV_LEN);
    const tag = raw.subarray(MAGIC.length + IV_LEN, MAGIC.length + IV_LEN + TAG_LEN);
    const decipher = createDecipheriv('aes-256-gcm', this.key, iv);
    decipher.setAAD(Buffer.from(key));
    decipher.setAuthTag(tag);
    // Throws if the file or tag was altered: tampering is never served as evidence
    return { data: Buffer.concat([decipher.update(raw.subarray(MAGIC.length + IV_LEN + TAG_LEN)), decipher.final()]), encrypted: true };
  }

  async get(key: string) {
    // GCM is verified at the end of the data, so decrypt fully before streaming anything (≤ 50 MB per file)
    const data = await this.read(key);
    return data ? Readable.from(data) : null;
  }

  remove(key: string) {
    return this.inner.remove(key);
  }
}

const driver: StorageDriver = env.STORAGE_DRIVER === 's3' ? s3FromEnv() : new LocalDiskStorage();
export const storageEncrypted = Boolean(env.EVIDENCE_ENCRYPTION_KEY);
export const storage: StorageDriver = env.EVIDENCE_ENCRYPTION_KEY
  ? new EncryptedStorage(driver, Buffer.from(env.EVIDENCE_ENCRYPTION_KEY, 'base64'))
  : driver;
/**
 * Reads an evidence object and reports whether it was stored encrypted. Throws when an encrypted
 * object fails authentication (altered on disk).
 */
export async function readObject(key: string): Promise<{ data: Buffer; encrypted: boolean } | null> {
  if (storage instanceof EncryptedStorage) return storage.readDetailed(key);
  const data = await storage.read(key);
  return data ? { data, encrypted: false } : null;
}

/** Raw driver, for tests and diagnostics only (reads files exactly as stored). */
export const rawStorage: StorageDriver = driver;
